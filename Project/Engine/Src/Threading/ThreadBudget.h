#pragma once

#include <cstdint>

namespace CoreEngine
{
    /// @brief プロセス全体で使えるワーカースレッド数の総量管理
    ///
    /// @details **存在意義は「プールの乱立でコア数を超えないこと」の一点。**
    ///          このエンジンには独立したスレッドプールが 3 つある
    ///          （AssetDatabase / TextureManager / ModelManager）。
    ///          各自が `hardware_concurrency / 2` を取ると、8 コア機で
    ///          4 + 4 + 4 = 12 ワーカー + メインスレッドになり、
    ///          物理コアの 1.6 倍のスレッドが同時に走る。
    ///          この状態では OS のスケジューラがタイムスライスを刻むだけで、
    ///          総スループットは上がらないのにレイテンシは悪化する。
    ///
    /// @details 2026-08-18 の「起動ステップが 2.2 秒かかっている」という誤診は、
    ///          メインスレッドの実作業 31ms に対して残りが**非同期プリロードの
    ///          ワーカーとの競合による待ち**だった。つまりこの問題は既に
    ///          実害として観測されている。
    ///
    /// @note 上限はコア数 - 1。メインスレッド（ウィンドウメッセージと描画）の
    ///       ぶんを必ず 1 本残す。ここを削るとフレームが飛ぶ。
    namespace ThreadBudget
    {
        /// @brief 割り当て可能なワーカー総数（コア数 - 1、最低 1）
        uint32_t GetCapacity();

        /// @brief 現在予約されている総ワーカー数
        uint32_t GetReserved();

        /// @brief ワーカー枠を予約する
        /// @param requested 希望数。0 なら「残り枠の半分」を既定として要求する
        /// @return 実際に割り当てられた数（最低 1。枠が尽きていても 1 は必ず返す）
        /// @note 最低 1 を返すのは、枠が尽きたときにワーカー 0 のプールを作らせないため。
        ///       ワーカー 0 のプールへ Submit したタスクは誰も実行せず、
        ///       future を待つ側が永久にブロックする。
        uint32_t Reserve(uint32_t requested);

        /// @brief 予約を返却する（ThreadPool のデストラクタから呼ばれる）
        void Release(uint32_t count);
    }
}
